import React, { useState, useMemo } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import { 
  X, Sparkles, Download, Copy, Check, ShieldCheck, AlertTriangle, 
  ArrowRight, FileCode, Code, Globe, RefreshCw, Layers, CheckCircle2, 
  Info, ExternalLink, Zap, CheckCircle
} from 'lucide-react';

export interface QuickFixItem {
  id: string;
  sourceUrl: string;
  canonicalUrl: string;
  statusCode?: number;
  reason: string;
  lastmod?: string;
  changefreq?: string;
  priority?: string;
  selected?: boolean;
}

interface RedirectQuickFixModalProps {
  isOpen: boolean;
  onClose: () => void;
  items: QuickFixItem[];
  onApplyFix?: (fixedItems: QuickFixItem[]) => void;
}

export default function RedirectQuickFixModal({
  isOpen,
  onClose,
  items,
  onApplyFix
}: RedirectQuickFixModalProps) {
  const [selectedIds, setSelectedIds] = useState<Set<string>>(() => new Set(items.map(i => i.id)));
  const [xmlFormat, setXmlFormat] = useState<'standard' | 'xhtml' | 'html-tags'>('standard');
  const [copied, setCopied] = useState(false);
  const [appliedNotice, setAppliedNotice] = useState<string | null>(null);

  // Sync selectedIds whenever items change
  React.useEffect(() => {
    setSelectedIds(new Set(items.map(i => i.id)));
  }, [items]);

  const toggleSelect = (id: string) => {
    setSelectedIds(prev => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  };

  const selectAll = () => {
    setSelectedIds(new Set(items.map(i => i.id)));
  };

  const deselectAll = () => {
    setSelectedIds(new Set());
  };

  const activeItems = useMemo(() => {
    return items.filter(i => selectedIds.has(i.id));
  }, [items, selectedIds]);

  // Generate Suggested Canonical XML Content
  const generatedSuggestedXml = useMemo(() => {
    if (activeItems.length === 0) return '<!-- No redirect entries selected for Quick-Fix -->';

    const todayStr = new Date().toISOString().split('T')[0];

    if (xmlFormat === 'html-tags') {
      const tags = activeItems.map(item => {
        return `<!-- Direct Canonical for 301 source: ${item.sourceUrl} -->\n<link rel="canonical" href="${item.canonicalUrl}" />`;
      });
      return tags.join('\n\n');
    }

    if (xmlFormat === 'xhtml') {
      const lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by Apex RedirectAuditor Quick-Fix Engine -->',
        '<!-- Eliminates Google Search Console 301 "Page with redirect" warnings -->',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
        '        xmlns:xhtml="http://www.w3.org/1999/xhtml">'
      ];

      activeItems.forEach(item => {
        lines.push('  <url>');
        lines.push(`    <loc>${item.canonicalUrl}</loc>`);
        lines.push(`    <xhtml:link rel="canonical" href="${item.canonicalUrl}" />`);
        lines.push(`    <lastmod>${item.lastmod || todayStr}</lastmod>`);
        lines.push(`    <changefreq>${item.changefreq || 'weekly'}</changefreq>`);
        lines.push(`    <priority>${item.priority || '0.80'}</priority>`);
        lines.push('  </url>');
      });

      lines.push('</urlset>');
      return lines.join('\n');
    }

    // Standard Canonical XML
    const lines = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<!-- Suggested Canonical Sitemap: Auto-Healed 301 Redirects -->',
      '<!-- Submit to Google Search Console to replace redirecting URLs with 200 OK canonicals -->',
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
    ];

    activeItems.forEach(item => {
      lines.push('  <url>');
      lines.push(`    <loc>${item.canonicalUrl}</loc>`);
      lines.push(`    <lastmod>${item.lastmod || todayStr}</lastmod>`);
      lines.push(`    <changefreq>${item.changefreq || 'weekly'}</changefreq>`);
      lines.push(`    <priority>${item.priority || '0.80'}</priority>`);
      lines.push('  </url>');
    });

    lines.push('</urlset>');
    return lines.join('\n');
  }, [activeItems, xmlFormat]);

  // Copy to clipboard
  const handleCopy = () => {
    navigator.clipboard.writeText(generatedSuggestedXml);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  // Download suggested XML file
  const handleDownload = () => {
    const filename = xmlFormat === 'html-tags' ? 'canonical-tags.html' : 'suggested-canonical-sitemap.xml';
    const mime = xmlFormat === 'html-tags' ? 'text/html' : 'application/xml';
    const blob = new Blob([generatedSuggestedXml], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  // Apply Quick-Fix callback & sync
  const handleApply = () => {
    if (onApplyFix) {
      onApplyFix(activeItems);
    }

    // Also sync to localStorage for the Sitemap Generator tool
    try {
      const todayStr = new Date().toISOString().split('T')[0];
      const routesToSync = activeItems.map(item => ({
        path: item.canonicalUrl.replace('https://apexutility.live', ''),
        changefreq: item.changefreq || 'weekly',
        priority: parseFloat(item.priority || '0.8'),
        lastmodDate: item.lastmod || todayStr,
        lastmodEnabled: true
      }));

      localStorage.setItem('apex_healed_sitemap_routes', JSON.stringify(routesToSync));
      setAppliedNotice(`Quick-Fix applied to ${activeItems.length} routes and synced to Sitemap Generator!`);
      setTimeout(() => setAppliedNotice(null), 4000);
    } catch (e) {
      console.error(e);
    }
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6 bg-black/80 backdrop-blur-md overflow-y-auto">
      <motion.div
        initial={{ opacity: 0, scale: 0.95, y: 15 }}
        animate={{ opacity: 1, scale: 1, y: 0 }}
        exit={{ opacity: 0, scale: 0.95, y: 15 }}
        className="bg-zinc-950 border border-zinc-800 rounded-2xl w-full max-w-4xl shadow-2xl overflow-hidden flex flex-col max-h-[90vh]"
      >
        {/* Modal Header */}
        <div className="bg-gradient-to-r from-red-950/80 via-zinc-900 to-zinc-950 border-b border-zinc-800 p-4 sm:p-5 flex items-center justify-between">
          <div className="space-y-1">
            <div className="flex items-center gap-2">
              <span className="bg-red-500/20 text-red-400 border border-red-500/30 text-[10px] font-mono px-2 py-0.5 rounded-full uppercase tracking-wider font-bold flex items-center gap-1">
                <Zap className="w-3 h-3 text-red-400" />
                Quick-Fix Engine
              </span>
              <span className="text-zinc-500 text-xs font-mono">Google Search Console Index Optimizer</span>
            </div>
            <h3 className="text-lg sm:text-xl font-extrabold text-white tracking-tight flex items-center gap-2 font-sans">
              Suggested Canonical XML Generator
            </h3>
            <p className="text-zinc-400 text-xs font-sans">
              Replaces detected 301 <span className="text-amber-300 font-mono">"Page with redirect"</span> paths with direct 200 OK canonical tags to eliminate crawler latency and accelerate indexing.
            </p>
          </div>

          <button
            onClick={onClose}
            className="text-zinc-400 hover:text-white p-2 rounded-xl bg-zinc-900 hover:bg-zinc-800 border border-zinc-800 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Applied Notification Banner */}
        <AnimatePresence>
          {appliedNotice && (
            <motion.div
              initial={{ opacity: 0, height: 0 }}
              animate={{ opacity: 1, height: 'auto' }}
              exit={{ opacity: 0, height: 0 }}
              className="bg-emerald-950/90 border-b border-emerald-800 text-emerald-200 px-4 py-2.5 text-xs font-mono flex items-center justify-between"
            >
              <div className="flex items-center gap-2">
                <CheckCircle className="w-4 h-4 text-emerald-400 shrink-0" />
                <span>{appliedNotice}</span>
              </div>
              <button onClick={() => setAppliedNotice(null)} className="text-emerald-400 hover:text-white">✕</button>
            </motion.div>
          )}
        </AnimatePresence>

        {/* Modal Body */}
        <div className="p-4 sm:p-6 overflow-y-auto space-y-6 flex-1 text-xs font-mono">
          {/* Quick Stats Bar */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
            <div className="bg-zinc-900/60 border border-zinc-800/80 rounded-xl p-3 space-y-1">
              <span className="text-[10px] text-zinc-500 uppercase tracking-wider block">Detected 301s</span>
              <div className="text-xl font-black text-amber-400 font-mono">{items.length}</div>
              <span className="text-[10px] text-zinc-400">Total redirect hazards</span>
            </div>

            <div className="bg-zinc-900/60 border border-zinc-800/80 rounded-xl p-3 space-y-1">
              <span className="text-[10px] text-zinc-500 uppercase tracking-wider block">Selected to Heal</span>
              <div className="text-xl font-black text-emerald-400 font-mono">{activeItems.length}</div>
              <span className="text-[10px] text-zinc-400">In suggested XML</span>
            </div>

            <div className="bg-zinc-900/60 border border-zinc-800/80 rounded-xl p-3 space-y-1">
              <span className="text-[10px] text-zinc-500 uppercase tracking-wider block">Target Status</span>
              <div className="text-xl font-black text-blue-400 font-mono">200 OK</div>
              <span className="text-[10px] text-zinc-400">Direct canonicals</span>
            </div>

            <div className="bg-zinc-900/60 border border-zinc-800/80 rounded-xl p-3 space-y-1">
              <span className="text-[10px] text-zinc-500 uppercase tracking-wider block">Crawl Hops Saved</span>
              <div className="text-xl font-black text-rose-400 font-mono">+{activeItems.length * 2}</div>
              <span className="text-[10px] text-zinc-400">Bot roundtrips spared</span>
            </div>
          </div>

          {/* Table of 301 Hazards and Canonical Replacements */}
          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold text-zinc-300 uppercase tracking-wider flex items-center gap-1.5">
                <AlertTriangle className="w-3.5 h-3.5 text-amber-400" />
                Detected 301 Redirect Entries &amp; Canonical Matches
              </span>
              <div className="flex items-center gap-2 text-[11px]">
                <button
                  type="button"
                  onClick={selectAll}
                  className="text-zinc-400 hover:text-white underline cursor-pointer"
                >
                  Select All
                </button>
                <span className="text-zinc-600">|</span>
                <button
                  type="button"
                  onClick={deselectAll}
                  className="text-zinc-400 hover:text-white underline cursor-pointer"
                >
                  Deselect All
                </button>
              </div>
            </div>

            <div className="border border-zinc-900 rounded-xl max-h-52 overflow-y-auto divide-y divide-zinc-900 bg-zinc-950">
              {items.length === 0 ? (
                <div className="p-8 text-center text-zinc-500 text-xs">
                  No 301 redirect entries currently detected.
                </div>
              ) : (
                items.map(item => {
                  const isChecked = selectedIds.has(item.id);
                  return (
                    <div
                      key={item.id}
                      onClick={() => toggleSelect(item.id)}
                      className={`p-3 flex items-start gap-3 cursor-pointer transition-colors ${
                        isChecked ? 'bg-zinc-900/40 hover:bg-zinc-900/70' : 'bg-zinc-950 opacity-60 hover:opacity-100'
                      }`}
                    >
                      <input
                        type="checkbox"
                        checked={isChecked}
                        onChange={() => toggleSelect(item.id)}
                        className="mt-1 accent-red-600 cursor-pointer"
                        onClick={(e) => e.stopPropagation()}
                      />

                      <div className="flex-1 space-y-1 min-w-0">
                        <div className="flex flex-wrap items-center gap-2">
                          <span className="bg-amber-500/15 border border-amber-500/30 text-amber-400 text-[9px] px-1.5 py-0.5 rounded font-bold">
                            {item.statusCode ? `HTTP ${item.statusCode}` : '301 Redirect'}
                          </span>
                          <span className="text-zinc-500 text-[10px]">{item.reason}</span>
                        </div>

                        <div className="space-y-0.5">
                          <div className="text-rose-400 text-[11px] line-through decoration-rose-500/50 break-all">
                            {item.sourceUrl}
                          </div>
                          <div className="flex items-center gap-1.5 text-emerald-400 text-xs font-bold break-all">
                            <ArrowRight className="w-3 h-3 text-emerald-400 shrink-0" />
                            <span>{item.canonicalUrl}</span>
                          </div>
                        </div>
                      </div>
                    </div>
                  );
                })
              )}
            </div>
          </div>

          {/* XML Format Selector & Code Preview */}
          <div className="space-y-2">
            <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-2">
              <span className="text-xs font-bold text-zinc-300 uppercase tracking-wider flex items-center gap-1.5">
                <FileCode className="w-3.5 h-3.5 text-red-400" />
                Suggested Canonical XML Preview
              </span>

              {/* Format Pills */}
              <div className="flex bg-zinc-900 p-0.5 rounded-lg border border-zinc-800 text-[10px]">
                <button
                  type="button"
                  onClick={() => setXmlFormat('standard')}
                  className={`px-2.5 py-1 rounded transition-colors cursor-pointer ${
                    xmlFormat === 'standard' ? 'bg-zinc-700 text-white font-bold' : 'text-zinc-400 hover:text-white'
                  }`}
                >
                  Standard &lt;loc&gt;
                </button>
                <button
                  type="button"
                  onClick={() => setXmlFormat('xhtml')}
                  className={`px-2.5 py-1 rounded transition-colors cursor-pointer ${
                    xmlFormat === 'xhtml' ? 'bg-zinc-700 text-white font-bold' : 'text-zinc-400 hover:text-white'
                  }`}
                >
                  XHTML &lt;canonical&gt;
                </button>
                <button
                  type="button"
                  onClick={() => setXmlFormat('html-tags')}
                  className={`px-2.5 py-1 rounded transition-colors cursor-pointer ${
                    xmlFormat === 'html-tags' ? 'bg-zinc-700 text-white font-bold' : 'text-zinc-400 hover:text-white'
                  }`}
                >
                  HTML &lt;link&gt; Tags
                </button>
              </div>
            </div>

            {/* Code Box */}
            <div className="relative">
              <pre className="p-4 bg-zinc-900/90 border border-zinc-800 rounded-xl text-emerald-400 text-[11px] leading-relaxed max-h-56 overflow-y-auto select-all whitespace-pre font-mono">
                {generatedSuggestedXml}
              </pre>

              <button
                type="button"
                onClick={handleCopy}
                className="absolute top-3 right-3 bg-zinc-800/80 hover:bg-zinc-700 text-white px-2.5 py-1 rounded text-[10px] border border-zinc-700 flex items-center gap-1 cursor-pointer transition-all"
              >
                {copied ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                <span>{copied ? 'Copied!' : 'Copy Code'}</span>
              </button>
            </div>
          </div>

          {/* Search Console Guidance Card */}
          <div className="bg-zinc-900/40 border border-zinc-900 rounded-xl p-3.5 space-y-1.5 text-zinc-400 text-[11px] font-sans">
            <div className="flex items-center gap-2 text-white font-bold font-mono text-xs">
              <Info className="w-3.5 h-3.5 text-blue-400 shrink-0" />
              <span>How this Quick-Fix resolves Google Search Console Indexing</span>
            </div>
            <p>
              Google Search Console's <em>"Page with redirect"</em> notice occurs when Googlebot crawls URLs containing obsolete query parameters (<code className="text-red-300 font-mono">/guides?id=...</code>) or aliases. By downloading or copying this suggested XML and updating your live <code className="text-zinc-200 font-mono">sitemap.xml</code>, Googlebot will replace the redirect chain with direct 200 OK crawls on its very next pass.
            </p>
          </div>
        </div>

        {/* Modal Footer Actions */}
        <div className="bg-zinc-900/80 border-t border-zinc-800 p-4 sm:p-5 flex flex-wrap items-center justify-between gap-3">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2 bg-zinc-900 hover:bg-zinc-800 text-zinc-400 hover:text-white rounded-xl text-xs font-mono border border-zinc-800 transition-colors cursor-pointer"
          >
            Close
          </button>

          <div className="flex flex-wrap items-center gap-2">
            <button
              type="button"
              onClick={handleApply}
              disabled={activeItems.length === 0}
              className="px-4 py-2 bg-zinc-800 hover:bg-zinc-700 text-amber-300 border border-amber-800/80 rounded-xl text-xs font-bold uppercase tracking-wider flex items-center gap-1.5 cursor-pointer transition-all disabled:opacity-40"
            >
              <Layers className="w-3.5 h-3.5 text-amber-400" />
              <span>Apply &amp; Sync to Generator</span>
            </button>

            <button
              type="button"
              onClick={handleDownload}
              disabled={activeItems.length === 0}
              className="px-5 py-2 bg-gradient-to-r from-red-600 to-rose-600 hover:from-red-500 hover:to-rose-500 text-white rounded-xl text-xs font-bold uppercase tracking-wider flex items-center gap-1.5 cursor-pointer transition-all shadow-lg shadow-red-950/30 disabled:opacity-40"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download Suggested XML ({activeItems.length})</span>
            </button>
          </div>
        </div>
      </motion.div>
    </div>
  );
}
